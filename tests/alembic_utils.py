"""Helpers to drive Alembic against an arbitrary database URL."""

from __future__ import annotations

import os
from contextlib import contextmanager
from pathlib import Path

from alembic import command
from alembic.config import Config

BASE_DIR = Path(__file__).resolve().parents[1]


def config_for(url: str) -> Config:
    config = Config(str(BASE_DIR / "alembic.ini"))
    config.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    return config


@contextmanager
def _database_url(url: str):
    """``migrations/env.py`` reads ``DATABASE_URL``; keep the suite's value intact."""

    previous = os.environ.get("DATABASE_URL")
    os.environ["DATABASE_URL"] = url
    try:
        yield
    finally:
        if previous is None:
            os.environ.pop("DATABASE_URL", None)
        else:
            os.environ["DATABASE_URL"] = previous


def upgrade(url: str, revision: str = "head") -> None:
    with _database_url(url):
        command.upgrade(config_for(url), revision)


def downgrade(url: str, revision: str = "base") -> None:
    with _database_url(url):
        command.downgrade(config_for(url), revision)


def check(url: str) -> None:
    """Raise ``AutogenerateDiffsDetected`` when models and DDL drift apart."""

    with _database_url(url):
        command.check(config_for(url))


def current_revision(url: str) -> str | None:
    from sqlalchemy import create_engine, text
    from sqlalchemy.pool import NullPool

    engine = create_engine(url, poolclass=NullPool)
    try:
        with engine.connect() as connection:
            row = connection.execute(text("SELECT version_num FROM alembic_version")).first()
            return row[0] if row else None
    finally:
        engine.dispose()
